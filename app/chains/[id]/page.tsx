import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { requireSuperadmin } from "@/lib/auth";
import { loadChain, loadChainMedia } from "@/lib/chains/data";
import { isUuid } from "@/lib/chains/validation";
import { ChainForm } from "@/components/ChainForm";
import { RunPanel } from "@/components/RunPanel";
import { AddStep, StepEditor } from "@/components/StepEditor";

const MAIN_APP_URL = process.env.NEXT_PUBLIC_MAIN_APP_URL;

export default async function ChainPage({ params }: { params: Promise<{ id: string }> }) {
  const admin = await requireSuperadmin();
  const { id } = await params;
  if (!isUuid(id)) notFound();
  const [loaded, media] = await Promise.all([loadChain(id), loadChainMedia(id, 30)]);
  if (!loaded) notFound();
  const { chain, steps, models } = loaded;
  const stepIds = steps.map((step) => step.id);

  return (
    <main className="flex flex-col gap-8">
      <div className="flex flex-col gap-3">
        <Link href="/" className="text-sm underline">
          ← All chains
        </Link>
        <h1 className="text-xl font-semibold">{chain.name}</h1>
        <ChainForm key={chain.id} chain={chain} />
      </div>

      <section className="flex flex-col gap-3">
        <h2 className="text-lg font-semibold">Steps ({steps.length})</h2>
        {steps.length === 0 && <p className="text-sm text-muted">No steps yet. Add the first one below.</p>}
        <ol className="flex flex-col gap-3">
          {steps.map((step) => (
            <StepEditor key={step.id} chainId={chain.id} step={step} stepIds={stepIds} models={models} />
          ))}
        </ol>
        <AddStep chainId={chain.id} models={models} nextNumber={steps.length + 1} />
        <p className="text-xs text-muted">
          The last step should answer with JSON like {'{"captions": ["...", "..."]}'} so its captions can be saved.
        </p>
      </section>

      <section className="flex flex-col gap-3">
        <h2 className="text-lg font-semibold">Generate</h2>
        <p className="text-sm text-muted">
          Runs this chain on a photo and shows what each step produced. Runs are saved as tests and listed below.
        </p>
        {MAIN_APP_URL ? (
          <RunPanel chainId={chain.id} userId={admin.id} stepCount={steps.length} mainAppUrl={MAIN_APP_URL} />
        ) : (
          <p className="text-sm font-semibold">NEXT_PUBLIC_MAIN_APP_URL is not set, so chains cannot be run from here.</p>
        )}
      </section>

      <section className="flex flex-col gap-3">
        <h2 className="text-lg font-semibold">Media generated by this chain ({media.length})</h2>
        {media.length === 0 && <p className="text-sm text-muted">Nothing yet. Generate above to see results here.</p>}
        <ul className="grid gap-3 md:grid-cols-2">
          {media.map((item) => (
            <li key={item.id} className="panel flex gap-3 p-3">
              <Image
                src={item.imageUrl}
                alt=""
                width={96}
                height={96}
                className="h-24 w-24 shrink-0 rounded bg-surface object-cover"
              />
              <div className="min-w-0 flex-1 text-sm">
                <p className="flex flex-wrap gap-x-2 text-xs text-muted">
                  <span>{new Date(item.createdAt).toLocaleString("en-US")}</span>
                  <span className="rounded border border-line px-1">
                    {item.isTest ? "test run" : item.isPosted ? "posted in the app" : "app draft"}
                  </span>
                  <span>{item.model}</span>
                </p>
                {item.note && <p className="mt-1 text-xs text-muted">Note: {item.note}</p>}
                <ol className="mt-1 list-decimal pl-5">
                  {item.captions.map((caption) => (
                    <li key={caption.position} className={caption.isWinner ? "font-semibold" : ""}>
                      {caption.text}
                      {caption.isWinner && " (posted winner)"}
                    </li>
                  ))}
                </ol>
              </div>
            </li>
          ))}
        </ul>
      </section>
    </main>
  );
}
